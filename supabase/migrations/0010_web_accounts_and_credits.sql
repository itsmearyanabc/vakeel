-- Overloading one table with both would mean the retention sweep deleting
-- someone's research history.
-- =============================================================================
CREATE TABLE IF NOT EXISTS chat_threads (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id      UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    -- Derived from the first message, editable by the user.
    title        VARCHAR(200) NOT NULL DEFAULT 'New chat',
    archived_at  TIMESTAMPTZ,

    -- Denormalised so the sidebar sorts without touching chat_messages.
    last_message_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    message_count   INTEGER NOT NULL DEFAULT 0,

    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- The sidebar query, exactly: this user's live threads, newest activity first.
CREATE INDEX IF NOT EXISTS idx_chat_threads_user
    ON chat_threads (user_id, last_message_at DESC) WHERE archived_at IS NULL;

DROP TRIGGER IF EXISTS trg_chat_threads_updated_at ON chat_threads;
CREATE TRIGGER trg_chat_threads_updated_at
    BEFORE UPDATE ON chat_threads
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();


CREATE TABLE IF NOT EXISTS chat_messages (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    thread_id       UUID NOT NULL REFERENCES chat_threads(id) ON DELETE CASCADE,
    -- Denormalised from the thread so a user's own history can be read, and
    -- purged, without a join.
    user_id         UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    role            VARCHAR(12) NOT NULL CHECK (role IN ('user', 'assistant')),
    content         TEXT NOT NULL,

    -- What produced this answer. Everything below is NULL on a user message.
    intent          query_intent,
    citations       TEXT[] NOT NULL DEFAULT ARRAY[]::TEXT[],
    -- Structured payload for renderable answers: precedent cards, case status.
    -- The web client can lay these out properly instead of parsing the
    -- WhatsApp-shaped text back into fields.
    structured      JSONB,

    model_used      VARCHAR(80),
    input_tokens    INTEGER NOT NULL DEFAULT 0,
    output_tokens   INTEGER NOT NULL DEFAULT 0,
    latency_ms      INTEGER NOT NULL DEFAULT 0,

    credits_charged INTEGER NOT NULL DEFAULT 0,
    guardrail_flagged BOOLEAN NOT NULL DEFAULT FALSE,
    guardrail_reason  TEXT,
    -- Set when generation failed. The message row still exists so the user sees
    -- what they asked and why it did not work, rather than their question
    -- vanishing.
    error_detail    TEXT,

    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_chat_messages_thread ON chat_messages (thread_id, created_at);
CREATE INDEX IF NOT EXISTS idx_chat_messages_user   ON chat_messages (user_id, created_at DESC);


-- =============================================================================
-- Credit functions
--
-- The arithmetic lives in SQL rather than in the service layer, for one
-- reason: atomicity. Read-balance-then-write in application code is a race, and
-- the losing side of that race is either a double spend or a lost purchase.
-- `UPDATE ... RETURNING` under a row lock is atomic by construction, and two
-- concurrent requests serialise instead of interleaving.
-- =============================================================================

-- -----------------------------------------------------------------------------
-- credit_refresh_free — roll the daily allowance over
--
-- Called at the start of every balance read and every spend. Idempotent within
-- a day: the guard on free_credits_date means the second call does nothing.
--
-- Expiry is recorded as its own ledger row before the top-up, so the history
-- reads honestly — "12 expired, 20 granted" rather than a bare "+8" that
-- implies the advocate was given eight credits.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION credit_refresh_free(
    p_user_id UUID,
    p_daily   INTEGER
)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
    v_current   INTEGER;
    v_date      DATE;
    v_today     DATE := CURRENT_DATE;
BEGIN
    -- FOR UPDATE: two requests arriving at 00:00:00 must not both decide they
    -- are the one to refill, or the ledger gets two grants for one day.
    SELECT free_credits, free_credits_date
      INTO v_current, v_date
      FROM users
     WHERE id = p_user_id
       FOR UPDATE;

    IF NOT FOUND THEN
        RETURN;
    END IF;

    -- Already refreshed today. The overwhelmingly common path.
    IF v_date IS NOT DISTINCT FROM v_today THEN
        RETURN;
    END IF;

    -- Yesterday's unused allowance lapses. Recorded rather than silently
    -- dropped: an advocate asking why their balance fell overnight deserves a
    -- row that says so.
    IF v_current > 0 AND v_date IS NOT NULL THEN
        INSERT INTO credit_ledger (user_id, kind, bucket, delta, balance_after, action, reason, reference)
        VALUES (
            p_user_id, 'EXPIRY', 'FREE', -v_current, 0, 'daily_rollover',
            format('%s unused free credit(s) from %s expired', v_current, v_date),
            format('expiry:%s:%s', p_user_id, v_date)
        )
        ON CONFLICT (reference) DO NOTHING;
    END IF;

    UPDATE users
       SET free_credits      = p_daily,
           free_credits_date = v_today
     WHERE id = p_user_id;

    IF p_daily > 0 THEN
        INSERT INTO credit_ledger (user_id, kind, bucket, delta, balance_after, action, reason, reference)
        VALUES (
            p_user_id, 'DAILY_GRANT', 'FREE', p_daily, p_daily, 'daily_allowance',
            format('Daily free allowance for %s', v_today),
            format('daily:%s:%s', p_user_id, v_today)
        )
        ON CONFLICT (reference) DO NOTHING;
    END IF;
END;
$$;


-- -----------------------------------------------------------------------------
-- credit_spend — charge for an action
--
-- Returns one row: whether it was allowed, the resulting balances, and what was
-- actually taken from each bucket.
--
-- Idempotent on p_reference. A replayed call — a retried request, a
-- double-clicked send — returns the original outcome and charges nothing more.
-- This is what makes it safe for the caller to retry on a network error, which
-- is the situation where double-charging otherwise happens.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION credit_spend(
    p_user_id   UUID,
    p_cost      INTEGER,
    p_action    VARCHAR,
    p_reference VARCHAR,
    p_daily     INTEGER
)
RETURNS TABLE (
    allowed       BOOLEAN,
    charged       INTEGER,
    free_left     INTEGER,
    paid_left     INTEGER,
    from_free     INTEGER,
    from_paid     INTEGER,
    already_spent BOOLEAN
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_free      INTEGER;
    v_paid      INTEGER;
    v_from_free INTEGER;
    v_from_paid INTEGER;
    v_existing  INTEGER;
BEGIN
    -- Replay check first, before anything is locked or moved.
    --
    -- Matched against the two exact suffixes rather than with LIKE. A pattern
    -- match would treat '%' or '_' inside a reference as a wildcard, and the
    -- failure mode is one spend suppressing an unrelated one.
    IF p_reference IS NOT NULL THEN
        SELECT COUNT(*) INTO v_existing
          FROM credit_ledger
         WHERE reference IN (p_reference || ':free', p_reference || ':paid')
           AND kind = 'SPEND';

        IF v_existing > 0 THEN
            SELECT u.free_credits, u.paid_credits INTO v_free, v_paid
              FROM users u WHERE u.id = p_user_id;
            RETURN QUERY SELECT TRUE, 0, COALESCE(v_free, 0), COALESCE(v_paid, 0), 0, 0, TRUE;
            RETURN;
        END IF;
    END IF;

    PERFORM credit_refresh_free(p_user_id, p_daily);

    SELECT u.free_credits, u.paid_credits
      INTO v_free, v_paid
      FROM users u
     WHERE u.id = p_user_id
       FOR UPDATE;

    IF NOT FOUND THEN
        RETURN QUERY SELECT FALSE, 0, 0, 0, 0, 0, FALSE;
        RETURN;
    END IF;

    IF v_free + v_paid < p_cost THEN
        RETURN QUERY SELECT FALSE, 0, v_free, v_paid, 0, 0, FALSE;
        RETURN;
    END IF;

    -- Free first. See the header for why the order is not arbitrary.
    v_from_free := LEAST(v_free, p_cost);
    v_from_paid := p_cost - v_from_free;

    UPDATE users
       SET free_credits = free_credits - v_from_free,
           paid_credits = paid_credits - v_from_paid
     WHERE id = p_user_id;

    -- One row per bucket touched, so no single row is ambiguous about which
    -- balance it moved. The reference is suffixed to keep both unique.
    IF v_from_free > 0 THEN
        INSERT INTO credit_ledger (user_id, kind, bucket, delta, balance_after, action, reason, reference)
        VALUES (p_user_id, 'SPEND', 'FREE', -v_from_free, v_free - v_from_free, p_action,
                format('%s (%s free credit(s))', p_action, v_from_free),
                p_reference || ':free');
    END IF;

    IF v_from_paid > 0 THEN
        INSERT INTO credit_ledger (user_id, kind, bucket, delta, balance_after, action, reason, reference)
        VALUES (p_user_id, 'SPEND', 'PAID', -v_from_paid, v_paid - v_from_paid, p_action,
                format('%s (%s paid credit(s))', p_action, v_from_paid),
                p_reference || ':paid');
    END IF;

    RETURN QUERY SELECT TRUE, p_cost, v_free - v_from_free, v_paid - v_from_paid,
                        v_from_free, v_from_paid, FALSE;
END;
$$;


-- -----------------------------------------------------------------------------
-- credit_grant — add credits to a bucket
--
-- Every inbound movement goes through here: signup bonus, admin grant, settled
-- purchase, refund. Idempotent on p_reference, which is what makes it safe to
-- call from a webhook handler that may be invoked more than once for one
-- payment.
--
-- Returns the new balance of the affected bucket, or the current one unchanged
-- when the reference was already applied.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION credit_grant(
    p_user_id   UUID,
    p_amount    INTEGER,
    p_kind      credit_entry_kind,
    p_bucket    credit_bucket,
    p_action    VARCHAR,
    p_reason    TEXT,
    p_reference VARCHAR,
    p_order_id  UUID DEFAULT NULL
)
RETURNS TABLE (
    applied   BOOLEAN,
    free_left INTEGER,
    paid_left INTEGER
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_free INTEGER;
    v_paid INTEGER;
    v_new  INTEGER;
BEGIN
    IF p_amount <= 0 THEN
        SELECT u.free_credits, u.paid_credits INTO v_free, v_paid FROM users u WHERE u.id = p_user_id;
        RETURN QUERY SELECT FALSE, COALESCE(v_free, 0), COALESCE(v_paid, 0);
        RETURN;
    END IF;

    IF p_reference IS NOT NULL AND EXISTS (SELECT 1 FROM credit_ledger WHERE reference = p_reference) THEN
        SELECT u.free_credits, u.paid_credits INTO v_free, v_paid FROM users u WHERE u.id = p_user_id;
        RETURN QUERY SELECT FALSE, COALESCE(v_free, 0), COALESCE(v_paid, 0);
        RETURN;
    END IF;

    SELECT u.free_credits, u.paid_credits
      INTO v_free, v_paid
      FROM users u
     WHERE u.id = p_user_id
       FOR UPDATE;

    IF NOT FOUND THEN
        RETURN QUERY SELECT FALSE, 0, 0;
        RETURN;
    END IF;

    IF p_bucket = 'FREE' THEN
        v_new := v_free + p_amount;
        UPDATE users SET free_credits = v_new WHERE id = p_user_id;
        v_free := v_new;
    ELSE
        v_new := v_paid + p_amount;
        UPDATE users SET paid_credits = v_new WHERE id = p_user_id;
        v_paid := v_new;
    END IF;

    INSERT INTO credit_ledger (user_id, kind, bucket, delta, balance_after, action, reason, reference, order_id)
    VALUES (p_user_id, p_kind, p_bucket, p_amount, v_new, p_action, p_reason, p_reference, p_order_id);

    RETURN QUERY SELECT TRUE, v_free, v_paid;
END;
$$;


-- -----------------------------------------------------------------------------
-- credit_refund — give back what a specific spend took
--
-- A claim is a promise to deliver an answer, and delivery can still fail after
-- the charge: WhatsApp refuses the send, the model times out, the process dies
-- mid-reply. Charging for an answer that never arrived is the wrong side of
-- that trade, so the spend is reversed.
--
-- ## Why this reverses the ledger rows rather than adding a fixed amount
--
-- A spend can straddle both buckets — three free credits and one paid — and a
-- naive refund of "4 credits" has to guess where they go. Guessing wrong either
-- converts paid credits into free ones that expire at midnight (the advocate
-- silently loses money) or free ones into paid (we silently give it away).
--
-- Reading the original SPEND rows removes the guess entirely: each is reversed
-- into the bucket it actually came from, for exactly the amount it took.
--
-- Idempotent, like everything else here: the refund rows carry their own
-- references, so a retried refund finds them already present and does nothing.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION credit_refund(
    p_user_id   UUID,
    p_reference VARCHAR,
    p_reason    TEXT
)
RETURNS TABLE (
    refunded  INTEGER,
    free_left INTEGER,
    paid_left INTEGER
)
LANGUAGE plpgsql
AS $$
DECLARE
    v_entry    RECORD;
    v_total    INTEGER := 0;
    v_free     INTEGER;
    v_paid     INTEGER;
    v_new      INTEGER;
    v_ref      VARCHAR;
BEGIN
    SELECT u.free_credits, u.paid_credits
      INTO v_free, v_paid
      FROM users u
     WHERE u.id = p_user_id
       FOR UPDATE;

    IF NOT FOUND THEN
        RETURN QUERY SELECT 0, 0, 0;
        RETURN;
    END IF;

    FOR v_entry IN
        SELECT bucket, delta, reference
          FROM credit_ledger
         WHERE user_id = p_user_id
           AND kind = 'SPEND'
           AND reference IN (p_reference || ':free', p_reference || ':paid')
    LOOP
        v_ref := replace(v_entry.reference, 'spend:', 'refund:');
        -- Suffix guards the case where a reference was not prefixed 'spend:'.
        IF v_ref = v_entry.reference THEN
            v_ref := 'refund:' || v_entry.reference;
        END IF;

        CONTINUE WHEN EXISTS (SELECT 1 FROM credit_ledger WHERE reference = v_ref);

        -- delta is negative on a SPEND, so negating it is the amount returned.
        IF v_entry.bucket = 'FREE' THEN
            v_new  := v_free - v_entry.delta;
            UPDATE users SET free_credits = v_new WHERE id = p_user_id;
            v_free := v_new;
        ELSE
            v_new  := v_paid - v_entry.delta;
            UPDATE users SET paid_credits = v_new WHERE id = p_user_id;
            v_paid := v_new;
        END IF;

        INSERT INTO credit_ledger (user_id, kind, bucket, delta, balance_after, action, reason, reference)
        VALUES (p_user_id, 'REFUND', v_entry.bucket, -v_entry.delta, v_new, 'refund', p_reason, v_ref);

        v_total := v_total - v_entry.delta;
    END LOOP;

    RETURN QUERY SELECT v_total, v_free, v_paid;
END;
$$;


