-- =============================================================================
-- 0010 — Web accounts, the credit wallet, and web chat threads
--
-- This migration turns a WhatsApp-only product into one with a signed-in web
-- application beside it. Three separate things are happening, and they are
-- worth reading in order because each depends on the one before it.
--
-- ## 1. An account is no longer a phone number
--
-- `users.phone_number` was UNIQUE NOT NULL, so the row and the handset were the
-- same fact. A web signup has no phone number at all, which that constraint
-- makes impossible to express. It becomes nullable, and a CHECK enforces the
-- thing actually required: an account must be reachable by *something* — a
-- phone number, an email address, or a federated identity.
--
-- Nullable UNIQUE is the correct shape here rather than a workaround. Postgres
-- treats NULLs as distinct, so any number of phone-less web accounts coexist
-- while a real number is still unique across the table, and the existing
-- `ON CONFLICT (phone_number)` upsert in UserRepository.findOrCreate keeps
-- working untouched.
--
-- ## 2. Credits become a ledger with two buckets
--
-- Until now "credits" were a daily counter in Redis mirrored to `daily_usage` —
-- a rate limit wearing the word credit. That is fine for throttling spend and
-- useless as an accounting record: it cannot answer "what did this advocate pay
-- for and what happened to it", which is the first question anyone asks once
-- money is involved.
--
-- `credit_ledger` is append-only and every balance change writes a row. The
-- balance is *also* denormalised onto `users` so a read is one indexed lookup
-- rather than a running sum, but `balance_after` on each row makes the two
-- reconcilable — if they ever disagree, the ledger is right and the cache is
-- wrong, and the disagreement is detectable instead of silent.
--
-- The two buckets are the part that matters for billing:
--
--   free_credits  — the daily allowance. Topped up to a fixed number each day,
--                   NOT accumulated. Yesterday's unused free credits are gone,
--                   which is what makes a daily allowance an allowance rather
--                   than an annuity.
--   paid_credits  — bought. Never expire, never reset, carried across days.
--
-- Spending draws down free first, then paid. Any other order would burn money
-- the advocate paid for while a free allowance expired unused beside it — the
-- kind of thing that produces support tickets and refund requests.
--
-- Collapsing these into one number is the mistake this design exists to avoid.
-- With a single balance, the nightly reset either wipes purchased credits or
-- lets free ones accumulate forever; there is no third option, and both are
-- wrong.
--
-- ## 3. Razorpay-shaped orders, with no gateway attached yet
--
-- `credit_orders` and `payment_events` model Razorpay's actual lifecycle. No
-- API calls are made anywhere in this build — but the schema commits to the
-- decisions that are expensive to change once rows exist:
--
--   - **Amounts are integer paise.** Razorpay's API is paise-denominated in
--     both directions. Storing rupees as NUMERIC means converting at every
--     boundary, and a division by 100 in the wrong place is a rounding error in
--     someone's money.
--   - **`receipt` is UNIQUE** and generated by us, so a double-submitted
--     checkout maps to one order rather than two.
--   - **Tax is broken out** at order time. Indian digital services attract GST,
--     and an invoice needs the base and tax components separately. Reconstructing
--     them later from a gross total is guesswork once the rate changes.
--   - **`payment_events` deduplicates webhooks.** Razorpay retries delivery
--     until it gets a 2xx, so `payment.captured` arriving three times is normal
--     operation, and crediting three times is not. Same defence as
--     `processed_webhooks` for Meta.
-- =============================================================================


-- -----------------------------------------------------------------------------
-- Enums
-- -----------------------------------------------------------------------------

-- What moved credits, and in which direction. The kind is what makes the ledger
-- readable months later: a bare +5 says nothing, 'DAILY_GRANT' says everything.
DO $$ BEGIN
    CREATE TYPE credit_entry_kind AS ENUM (
        'DAILY_GRANT',    -- the free allowance, topped up once per day
        'SIGNUP_BONUS',   -- one-off welcome credits
        'ADMIN_GRANT',    -- granted by hand from the admin panel
        'PURCHASE',       -- paid for, via a settled credit_orders row
        'SPEND',          -- consumed by an action (negative)
        'REFUND',         -- an action was charged but never delivered (positive)
        'EXPIRY',         -- free credits cleared at the daily rollover (negative)
        'ADJUSTMENT'      -- manual correction; always carries a reason
    );
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- Which bucket an entry moved. Recorded per entry so a spend that straddles
-- both buckets is two rows, and neither is ambiguous about what it drew down.
DO $$ BEGIN
    CREATE TYPE credit_bucket AS ENUM ('FREE', 'PAID');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- Razorpay's order lifecycle, plus the CREATED state that exists before the
-- gateway has seen it at all.
DO $$ BEGIN
    CREATE TYPE payment_order_status AS ENUM (
        'CREATED',    -- our row exists; checkout not yet completed
        'ATTEMPTED',  -- the gateway reports at least one payment attempt
        'PAID',       -- captured and credited
        'FAILED',     -- the attempt failed and will not be retried
        'REFUNDED'    -- money returned; credits clawed back
    );
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- How an account came to exist. Purely descriptive, but it is the difference
-- between "web signups are flat" and "we have no idea where users come from".
DO $$ BEGIN
    CREATE TYPE account_source AS ENUM ('WHATSAPP', 'WEB_PASSWORD', 'WEB_GOOGLE');
EXCEPTION WHEN duplicate_object THEN NULL; END $$;


