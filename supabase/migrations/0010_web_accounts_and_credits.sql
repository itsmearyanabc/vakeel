--
-- Same posture as 0005: the application connects as the owner and bypasses RLS,
-- and these policies exist so the intent is written down in the schema rather
-- than assumed. Everything here is either credentials or personal data, so
-- there is no public-read table among them.
-- =============================================================================
ALTER TABLE user_identities ENABLE ROW LEVEL SECURITY;
ALTER TABLE web_sessions    ENABLE ROW LEVEL SECURITY;
ALTER TABLE auth_tokens     ENABLE ROW LEVEL SECURITY;
ALTER TABLE credit_ledger   ENABLE ROW LEVEL SECURITY;
ALTER TABLE credit_orders   ENABLE ROW LEVEL SECURITY;
ALTER TABLE payment_events  ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_threads    ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_messages   ENABLE ROW LEVEL SECURITY;

-- FORCE so that even the table owner is subject to policy. Session tokens and
-- payment records are the two things in this schema where an accidental
-- unfiltered query is most expensive.
ALTER TABLE web_sessions   FORCE ROW LEVEL SECURITY;
ALTER TABLE auth_tokens    FORCE ROW LEVEL SECURITY;
ALTER TABLE credit_ledger  FORCE ROW LEVEL SECURITY;
ALTER TABLE credit_orders  FORCE ROW LEVEL SECURITY;

DO $$
DECLARE
    t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'user_identities', 'web_sessions', 'auth_tokens', 'credit_ledger',
        'credit_orders', 'payment_events', 'chat_threads', 'chat_messages'
    ]
    LOOP
        EXECUTE format('DROP POLICY IF EXISTS %I ON %I', t || '_service_all', t);
        EXECUTE format(
            'CREATE POLICY %I ON %I FOR ALL TO service_role USING (true) WITH CHECK (true)',
            t || '_service_all', t
        );
    END LOOP;
END $$;


-- =============================================================================
-- Backfill
--
-- Existing rows all arrived over WhatsApp, which is already the column default,
-- so signup_source needs nothing. The wallet does: every existing advocate
-- starts with an empty free bucket and no date, which credit_refresh_free()
-- reads as stale and fills on their next action. That is the correct outcome —
-- granting here would write a ledger row dated to the migration rather than to
-- the day the allowance was actually used.
-- =============================================================================

-- `daily_usage` and `claim_daily_quota()` are superseded by this ledger and are
-- no longer written to. They are deliberately NOT dropped: the rows are a real
-- record of what happened before this migration, and a DROP would destroy the
-- only copy of it to save a table nobody reads. Anything that needs historical
-- usage should read `daily_usage` for dates before the deployment of 0010 and
-- `credit_ledger` after it.
COMMENT ON TABLE daily_usage IS
    'SUPERSEDED by credit_ledger (migration 0010). Retained read-only for pre-0010 history; nothing writes here.';

COMMENT ON TABLE credit_ledger IS
    'Append-only record of every credit movement. Never UPDATE or DELETE a row; write a compensating entry instead.';
COMMENT ON TABLE credit_orders IS
    'Credit purchases. Amounts are integer PAISE, matching Razorpay. base_paise + tax_paise = amount_paise.';
COMMENT ON TABLE payment_events IS
    'Deduplicated gateway webhooks, keyed on the provider event id. Razorpay retries until 2xx.';
COMMENT ON COLUMN credit_ledger.reference IS
    'Idempotency key. UNIQUE, and supplied by every writer: daily:{user}:{date}, spend:{message}:{bucket}, order:{payment_id}.';
