-- users — web identity columns
-- =============================================================================

-- The identity change described in the header. Dropped rather than replaced:
-- the UNIQUE index stays, and NULLs do not collide under it.
ALTER TABLE users ALTER COLUMN phone_number DROP NOT NULL;

ALTER TABLE users ADD COLUMN IF NOT EXISTS email               VARCHAR(320);
ALTER TABLE users ADD COLUMN IF NOT EXISTS password_hash       TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_verified_at   TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS phone_verified_at   TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS avatar_url          TEXT;
ALTER TABLE users ADD COLUMN IF NOT EXISTS signup_source       account_source NOT NULL DEFAULT 'WHATSAPP';
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_web_login_at   TIMESTAMPTZ;

-- The wallet, denormalised. Authoritative for reads; credit_ledger is
-- authoritative for truth. See the header on why these are two columns.
ALTER TABLE users ADD COLUMN IF NOT EXISTS free_credits        INTEGER NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS free_credits_date   DATE;
ALTER TABLE users ADD COLUMN IF NOT EXISTS paid_credits        INTEGER NOT NULL DEFAULT 0;

-- Neither bucket may go negative. A spend that would breach this is a bug in
-- the spend function, and it should fail loudly at the constraint rather than
-- quietly hand out credit nobody has.
DO $$ BEGIN
    ALTER TABLE users ADD CONSTRAINT users_credits_non_negative
        CHECK (free_credits >= 0 AND paid_credits >= 0);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- An account has to be reachable somehow. Without this, a bug that nulls a
-- phone number produces a row nobody can ever sign into and nothing detects.
DO $$ BEGIN
    ALTER TABLE users ADD CONSTRAINT users_has_an_identity
        CHECK (phone_number IS NOT NULL OR email IS NOT NULL);
EXCEPTION WHEN duplicate_object THEN NULL; END $$;

-- Email uniqueness is enforced on the lowercased value, not the stored one.
-- Addresses are compared case-insensitively by every mail system on earth, so
-- a UNIQUE on the raw column would happily accept Advocate@example.com beside
-- advocate@example.com and hand the same person two accounts.
CREATE UNIQUE INDEX IF NOT EXISTS idx_users_email_lower
    ON users (lower(email)) WHERE email IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_users_signup_source ON users (signup_source);

COMMENT ON COLUMN users.email IS
    'Login address for the web app. Stored as entered; uniqueness is enforced on lower(email).';
COMMENT ON COLUMN users.password_hash IS
    'scrypt, encoded as scrypt$N$r$p$salt$hash. NULL for accounts that only ever signed in with Google or WhatsApp.';
COMMENT ON COLUMN users.free_credits IS
    'Daily allowance remaining today. Reset — not incremented — at the first action after midnight. See credit_refresh_free().';
-- "Paid" names the common case, but the property that matters is durability:
-- anything in this bucket survives the nightly rollover. Purchases land here,
-- and so do signup bonuses and admin grants, because a credit someone was given
-- as compensation expiring at midnight is the same broken promise as a
-- purchased one expiring.
COMMENT ON COLUMN users.paid_credits IS
    'Durable credits - purchased, bonus or granted. Never expire and never reset. Spent only after free_credits is exhausted.';
COMMENT ON COLUMN users.free_credits_date IS
    'The date free_credits belongs to. A value older than CURRENT_DATE means the bucket is stale and is refilled on next touch.';


-- =============================================================================
-- user_identities — federated logins
--
-- Separate from users because one account can legitimately have several: an
-- advocate who signs up with a password and later clicks "continue with Google"
-- must land on the *same* account, not a duplicate. The UNIQUE is on
-- (provider, provider_account_id) rather than on the email, because a Google
-- account's email can change while its `sub` cannot — matching on email would
-- silently detach the identity the day someone changes their address.
-- =============================================================================
CREATE TABLE IF NOT EXISTS user_identities (
    id                  UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id             UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    provider            VARCHAR(32) NOT NULL,        -- 'google'
    -- Google's `sub`. Stable for the life of the account, unlike the email.
    provider_account_id VARCHAR(255) NOT NULL,

    -- What the provider told us at link time. Kept for support ("which Google
    -- account is this?") and never used for matching.
    email               VARCHAR(320),
    display_name        VARCHAR(200),
    avatar_url          TEXT,

    last_login_at       TIMESTAMPTZ,
    created_at          TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    UNIQUE (provider, provider_account_id)
);

CREATE INDEX IF NOT EXISTS idx_user_identities_user ON user_identities (user_id);


-- =============================================================================
-- web_sessions
--
-- Opaque random tokens, not JWTs. The admin panel uses a JWT because it has no
-- session store and one operator; end-user sessions have neither excuse. The
-- deciding property is revocation: a stolen JWT is valid until it expires and
-- nothing can stop it, whereas deleting a row here signs that device out on its
-- next request. "Sign out all devices" is a DELETE, not a key rotation.
--
-- Only the SHA-256 of the token is stored. A database leak therefore yields
-- nothing usable — the same reasoning as password hashing, applied to the
-- credential the token actually is.
-- =============================================================================
CREATE TABLE IF NOT EXISTS web_sessions (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id      UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    -- SHA-256 hex of the cookie value. Never the value itself.
    token_hash   CHAR(64) NOT NULL UNIQUE,

    -- Truncated and coarse on purpose: enough to show "Chrome on Windows,
    -- Mumbai" in a session list, not enough to be a tracking record.
    user_agent   VARCHAR(300),
    ip_address   INET,

    expires_at   TIMESTAMPTZ NOT NULL,
    last_used_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    revoked_at   TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_web_sessions_user   ON web_sessions (user_id, created_at DESC);
-- Partial: the expiry sweep only ever looks at sessions still considered live.
CREATE INDEX IF NOT EXISTS idx_web_sessions_expiry ON web_sessions (expires_at) WHERE revoked_at IS NULL;


-- =============================================================================
-- auth_tokens — email verification, password reset, phone linking
--
-- One table rather than three, because all three are the same object: a
-- single-use secret with an expiry, a purpose and a consumed-at timestamp.
-- Hashed for the same reason session tokens are — a reset token in a leaked
-- backup is an account takeover.
--
-- `consumed_at` rather than a DELETE so a user who clicks a reset link twice
-- gets "this link has already been used" instead of "invalid link", which reads
-- like an attack to a support agent and like a broken product to a user.
-- =============================================================================
CREATE TABLE IF NOT EXISTS auth_tokens (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id     UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    purpose     VARCHAR(32) NOT NULL,   -- EMAIL_VERIFY | PASSWORD_RESET | PHONE_LINK
    token_hash  CHAR(64) NOT NULL UNIQUE,

    -- Phone linking carries the number being claimed, so the code cannot be
    -- replayed against a different number than the one it was issued for.
    subject     VARCHAR(320),

    expires_at  TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    attempts    SMALLINT NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_auth_tokens_user    ON auth_tokens (user_id, purpose);
CREATE INDEX IF NOT EXISTS idx_auth_tokens_expiry  ON auth_tokens (expires_at) WHERE consumed_at IS NULL;


-- =============================================================================
-- credit_ledger — append-only
--
-- Never UPDATEd and never DELETEd outside the retention sweep. A correction is
-- a new compensating row, which is what makes the history reconstructable: an
-- edited ledger cannot answer "what did this look like on the 3rd".
-- =============================================================================
CREATE TABLE IF NOT EXISTS credit_ledger (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id       UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    kind          credit_entry_kind NOT NULL,
    bucket        credit_bucket     NOT NULL,

    -- Signed. Negative for SPEND and EXPIRY, positive for everything else.
    -- Deliberately not split into debit/credit columns: one signed integer
    -- cannot disagree with itself, and SUM(delta) is the balance by definition.
    delta         INTEGER NOT NULL,

    -- The bucket's balance immediately after this row was written. Makes the
    -- denormalised columns on `users` auditable without replaying the ledger.
    balance_after INTEGER NOT NULL,

    -- What was bought or spent: 'SECTION_LOOKUP', 'PRECEDENT_SEARCH', 'pack:500'.
    action        VARCHAR(60),
    -- Human-readable, shown in the user's own credit history.
    reason        TEXT,

    -- The idempotency key, and the reason this column is UNIQUE.
    --
    -- Every writer supplies one: 'daily:{user}:{date}', 'spend:{message_id}',
    -- 'order:{razorpay_payment_id}'. A retried webhook, a double-clicked send
    -- button or a re-run grant collides here and is rejected by the index
    -- rather than being applied twice. This is the single most important
    -- constraint in the table.
    reference     VARCHAR(200) UNIQUE,

    -- Set for PURCHASE and REFUND rows.
    order_id      UUID,

    metadata      JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- A zero-delta entry is always a bug: either the caller meant to move
    -- credits and computed the amount wrong, or it should not have written a
    -- row at all.
    CONSTRAINT credit_ledger_delta_non_zero CHECK (delta <> 0)
);

CREATE INDEX IF NOT EXISTS idx_credit_ledger_user_time ON credit_ledger (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_credit_ledger_kind      ON credit_ledger (kind, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_credit_ledger_order     ON credit_ledger (order_id) WHERE order_id IS NOT NULL;


-- =============================================================================
-- credit_orders — Razorpay-shaped, gateway not yet attached
--
-- Amounts are INTEGER PAISE throughout. See the header for why this is not
-- NUMERIC rupees.
-- =============================================================================
CREATE TABLE IF NOT EXISTS credit_orders (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id            UUID NOT NULL REFERENCES users(id) ON DELETE CASCADE,

    -- Our idempotency key, sent to Razorpay as `receipt`. Generated before the
    -- gateway is contacted, so a request that times out mid-flight can be
    -- retried without risking a second order.
    receipt            VARCHAR(64) NOT NULL UNIQUE,

    -- What the advocate gets. Fixed at order time so a later price change
    -- cannot alter what an already-paid order was worth.
    credits            INTEGER NOT NULL CHECK (credits > 0),
    pack_code          VARCHAR(40),

    -- Money, in paise. base + tax = amount_paise, enforced below.
    amount_paise       INTEGER NOT NULL CHECK (amount_paise > 0),
    base_paise         INTEGER NOT NULL CHECK (base_paise > 0),
    tax_paise          INTEGER NOT NULL DEFAULT 0 CHECK (tax_paise >= 0),
    -- Basis points, so 18% is 1800 and no fraction is lost to rounding.
    tax_rate_bps       INTEGER NOT NULL DEFAULT 0,
    currency           CHAR(3) NOT NULL DEFAULT 'INR',

    status             payment_order_status NOT NULL DEFAULT 'CREATED',

    -- Gateway identifiers. NULL until the corresponding step happens.
    razorpay_order_id  VARCHAR(64) UNIQUE,
    razorpay_payment_id VARCHAR(64) UNIQUE,
    -- The checkout signature, retained for dispute evidence.
    razorpay_signature VARCHAR(128),
    payment_method     VARCHAR(32),          -- upi | card | netbanking | wallet
    failure_reason     TEXT,

    -- Set when the PURCHASE ledger row is written, which is what makes
    -- "paid but not credited" a detectable state rather than an invisible one.
    credited_at        TIMESTAMPTZ,
    refunded_at        TIMESTAMPTZ,

    notes              JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- The invoice must add up. A mismatch here is an invoice that cannot be
    -- filed, and it is far cheaper to catch on INSERT than in an audit.
    CONSTRAINT credit_orders_amount_adds_up CHECK (base_paise + tax_paise = amount_paise)
);

CREATE INDEX IF NOT EXISTS idx_credit_orders_user   ON credit_orders (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_credit_orders_status ON credit_orders (status, created_at DESC);
-- Finds orders the gateway says are paid but which never produced credits.
CREATE INDEX IF NOT EXISTS idx_credit_orders_uncredited
    ON credit_orders (created_at) WHERE status = 'PAID' AND credited_at IS NULL;

DROP TRIGGER IF EXISTS trg_credit_orders_updated_at ON credit_orders;
CREATE TRIGGER trg_credit_orders_updated_at
    BEFORE UPDATE ON credit_orders
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();

-- Deferred rather than inline on credit_ledger, because the two tables
-- reference each other conceptually and one has to be created first.
DO $$ BEGIN
    ALTER TABLE credit_ledger ADD CONSTRAINT credit_ledger_order_fk
        FOREIGN KEY (order_id) REFERENCES credit_orders(id) ON DELETE SET NULL;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;


-- =============================================================================
-- payment_events — webhook idempotency
--
-- Razorpay redelivers until it receives a 2xx, so the same `payment.captured`
-- arriving repeatedly is normal. Crediting on each delivery is not. Identical
-- in purpose to `processed_webhooks` for Meta, kept separate because the
-- lifetimes and the retention rules differ: a payment event is a financial
-- record and outlives a chat webhook by a long way.
-- =============================================================================
CREATE TABLE IF NOT EXISTS payment_events (
    -- Razorpay's `x-razorpay-event-id` header. The dedupe key.
    event_id     VARCHAR(120) PRIMARY KEY,
    event_type   VARCHAR(60) NOT NULL,
    order_id     UUID REFERENCES credit_orders(id) ON DELETE SET NULL,

    -- The verified body, kept verbatim. When a payment is disputed months
    -- later, what the gateway actually sent is the only account that matters.
    payload      JSONB NOT NULL DEFAULT '{}'::jsonb,
    -- False when the signature verified but the event was not one we act on.
    handled      BOOLEAN NOT NULL DEFAULT FALSE,
    error_detail TEXT,

    received_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_payment_events_time  ON payment_events (received_at DESC);
CREATE INDEX IF NOT EXISTS idx_payment_events_order ON payment_events (order_id);


-- =============================================================================
-- chat_threads / chat_messages — the web conversation
--
-- The WhatsApp side has no equivalent because WhatsApp *is* the thread; the web
-- app has a sidebar full of them, which means they need identity and ordering.
--
-- Not merged with `whatsapp_messages`: that table is a delivery log keyed on
-- Meta's message id, with delivery statuses and a 90-day retention. This is
